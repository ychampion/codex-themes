package export

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/ychampion/codex-themes/internal/theme"
)

type Format string

const (
	FormatWindowsTerminal Format = "windows-terminal"
	FormatITerm2          Format = "iterm2"
	FormatGhostty         Format = "ghostty"
	FormatAlacritty       Format = "alacritty"
	FormatANSI            Format = "ansi"
)

func AllFormats() []Format {
	return []Format{FormatWindowsTerminal, FormatITerm2, FormatGhostty, FormatAlacritty, FormatANSI}
}

func ParseFormat(value string) (Format, error) {
	format := Format(strings.ToLower(strings.TrimSpace(value)))
	for _, supported := range AllFormats() {
		if format == supported {
			return format, nil
		}
	}
	return "", fmt.Errorf("unsupported export format %q", value)
}

func Render(manifest theme.Manifest, format Format) ([]byte, error) {
	switch format {
	case FormatWindowsTerminal:
		return renderWindowsTerminal(manifest)
	case FormatGhostty:
		return renderGhostty(manifest), nil
	case FormatAlacritty:
		return renderAlacritty(manifest), nil
	case FormatITerm2:
		return renderITerm2(manifest), nil
	case FormatANSI:
		return renderANSI(manifest), nil
	default:
		return nil, fmt.Errorf("unsupported export format %q", format)
	}
}

func Filename(manifest theme.Manifest, format Format) string {
	base := manifest.ID
	switch format {
	case FormatWindowsTerminal:
		return base + ".windows-terminal.json"
	case FormatGhostty:
		return base + ".ghostty"
	case FormatAlacritty:
		return base + ".alacritty.toml"
	case FormatITerm2:
		return base + ".itermcolors"
	case FormatANSI:
		return base + ".ansi.json"
	default:
		return base + ".txt"
	}
}

func renderWindowsTerminal(manifest theme.Manifest) ([]byte, error) {
	scheme := map[string]any{
		"name":                firstNonEmpty(manifest.Targets.WindowsTerminal.SchemeName, manifest.Name),
		"background":          manifest.TokenOr("bg_primary", "#000000"),
		"foreground":          manifest.TokenOr("fg_primary", "#FFFFFF"),
		"cursorColor":         manifest.TokenOr("cursor", manifest.TokenOr("accent_primary", "#FFFFFF")),
		"selectionBackground": manifest.TokenOr("selection_bg", manifest.TokenOr("accent_soft", "#333333")),
		"black":               manifest.ANSI["black"],
		"red":                 manifest.ANSI["red"],
		"green":               manifest.ANSI["green"],
		"yellow":              manifest.ANSI["yellow"],
		"blue":                manifest.ANSI["blue"],
		"purple":              manifest.ANSI["magenta"],
		"cyan":                manifest.ANSI["cyan"],
		"white":               manifest.ANSI["white"],
		"brightBlack":         manifest.ANSI["bright_black"],
		"brightRed":           manifest.ANSI["bright_red"],
		"brightGreen":         manifest.ANSI["bright_green"],
		"brightYellow":        manifest.ANSI["bright_yellow"],
		"brightBlue":          manifest.ANSI["bright_blue"],
		"brightPurple":        manifest.ANSI["bright_magenta"],
		"brightCyan":          manifest.ANSI["bright_cyan"],
		"brightWhite":         manifest.ANSI["bright_white"],
	}
	return json.MarshalIndent(scheme, "", "  ")
}

func renderGhostty(manifest theme.Manifest) []byte {
	var buffer bytes.Buffer
	buffer.WriteString("# Generated by Codex Themes\n")
	buffer.WriteString(fmt.Sprintf("background = %s\n", manifest.TokenOr("bg_primary", "#000000")))
	buffer.WriteString(fmt.Sprintf("foreground = %s\n", manifest.TokenOr("fg_primary", "#FFFFFF")))
	buffer.WriteString(fmt.Sprintf("cursor-color = %s\n", manifest.TokenOr("cursor", manifest.TokenOr("accent_primary", "#FFFFFF"))))
	buffer.WriteString(fmt.Sprintf("selection-background = %s\n", manifest.TokenOr("selection_bg", manifest.TokenOr("accent_soft", "#333333"))))
	ansiOrder := []string{"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white", "bright_black", "bright_red", "bright_green", "bright_yellow", "bright_blue", "bright_magenta", "bright_cyan", "bright_white"}
	for index, key := range ansiOrder {
		buffer.WriteString(fmt.Sprintf("palette = %d=%s\n", index, manifest.ANSI[key]))
	}
	return buffer.Bytes()
}

func renderAlacritty(manifest theme.Manifest) []byte {
	var buffer bytes.Buffer
	buffer.WriteString("# Generated by Codex Themes\n")
	buffer.WriteString("[colors.primary]\n")
	buffer.WriteString(fmt.Sprintf("background = \"%s\"\n", manifest.TokenOr("bg_primary", "#000000")))
	buffer.WriteString(fmt.Sprintf("foreground = \"%s\"\n\n", manifest.TokenOr("fg_primary", "#FFFFFF")))
	buffer.WriteString("[colors.cursor]\n")
	buffer.WriteString(fmt.Sprintf("cursor = \"%s\"\n", manifest.TokenOr("cursor", manifest.TokenOr("accent_primary", "#FFFFFF"))))
	buffer.WriteString(fmt.Sprintf("text = \"%s\"\n\n", manifest.TokenOr("fg_inverse", "#000000")))
	buffer.WriteString("[colors.selection]\n")
	buffer.WriteString(fmt.Sprintf("background = \"%s\"\n", manifest.TokenOr("selection_bg", manifest.TokenOr("accent_soft", "#333333"))))
	buffer.WriteString(fmt.Sprintf("text = \"%s\"\n\n", manifest.TokenOr("selection_fg", manifest.TokenOr("fg_primary", "#FFFFFF"))))
	buffer.WriteString("[colors.normal]\n")
	for _, key := range []string{"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"} {
		buffer.WriteString(fmt.Sprintf("%s = \"%s\"\n", colorKeyForTOML(key), manifest.ANSI[key]))
	}
	buffer.WriteString("\n[colors.bright]\n")
	for _, key := range []string{"bright_black", "bright_red", "bright_green", "bright_yellow", "bright_blue", "bright_magenta", "bright_cyan", "bright_white"} {
		buffer.WriteString(fmt.Sprintf("%s = \"%s\"\n", colorKeyForTOML(key), manifest.ANSI[key]))
	}
	return buffer.Bytes()
}

func renderITerm2(manifest theme.Manifest) []byte {
	makeEntry := func(name, hex string) string {
		r, g, b := hexToFloatTriplet(hex)
		return fmt.Sprintf("<key>%s</key><dict><key>Blue Component</key><real>%.6f</real><key>Green Component</key><real>%.6f</real><key>Red Component</key><real>%.6f</real></dict>", name, b, g, r)
	}
	entries := []string{
		makeEntry("Background Color", manifest.TokenOr("bg_primary", "#000000")),
		makeEntry("Foreground Color", manifest.TokenOr("fg_primary", "#FFFFFF")),
		makeEntry("Cursor Color", manifest.TokenOr("cursor", manifest.TokenOr("accent_primary", "#FFFFFF"))),
		makeEntry("Selection Color", manifest.TokenOr("selection_bg", manifest.TokenOr("accent_soft", "#333333"))),
	}
	return []byte("<?xml version=\"1.0\" encoding=\"UTF-8\"?><plist version=\"1.0\"><dict>" + strings.Join(entries, "") + "</dict></plist>")
}

func renderANSI(manifest theme.Manifest) []byte {
	payload := map[string]any{
		"name":       manifest.Name,
		"appearance": manifest.Appearance,
		"ansi":       manifest.ANSI,
	}
	bytes, _ := json.MarshalIndent(payload, "", "  ")
	return bytes
}

func colorKeyForTOML(name string) string {
	return strings.TrimPrefix(name, "bright_")
}

func hexToFloatTriplet(value string) (float64, float64, float64) {
	parse := func(segment string) float64 {
		var v uint8
		fmt.Sscanf(segment, "%02X", &v)
		return float64(v) / 255
	}
	trimmed := strings.TrimPrefix(strings.ToUpper(value), "#")
	if len(trimmed) < 6 {
		return 0, 0, 0
	}
	return parse(trimmed[0:2]), parse(trimmed[2:4]), parse(trimmed[4:6])
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if strings.TrimSpace(value) != "" {
			return value
		}
	}
	return ""
}


